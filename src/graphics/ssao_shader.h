/* Shared HLSL; depth reconstruction uses the draw camera inverse projection. */
#ifndef TSFP_SSAO_SHADER_H
#define TSFP_SSAO_SHADER_H
static const char tsfp_ssao_shader[] =
"// Half-resolution depth-derived obscurance. No temporal history or random jitter.\n"
"cbuffer AOConstants : register(b7) {\n"
"    row_major float4x4 inverse_projection;\n"
"    float4 size; // full width/height, half width/height\n"
"    float4 origin; // source viewport origin in pixels\n"
"    float4 settings; // world radius, bias fraction, strength, projection Y scale\n"
"};\n"
"#if DEPTH_SAMPLES > 1\n"
"Texture2DMS<float> scene_depth : register(t9);\n"
"float depth_at(int2 pixel) { pixel+=int2(origin.xy);\n"
"    float nearest=1;\n"
"    [unroll]for(int i=0;i<DEPTH_SAMPLES;i++)nearest=min(nearest,scene_depth.Load(pixel,i));\n"
"    return nearest;\n"
"}\n"
"#else\n"
"Texture2D<float> scene_depth : register(t9);\n"
"float depth_at(int2 pixel) { pixel+=int2(origin.xy); return scene_depth.Load(int3(pixel,0)); }\n"
"#endif\n"
"float4 vs_main(uint id : SV_VertexID) : SV_Position {\n"
"    float2 c=float2((id<<1)&2,id&2);\n"
"    return float4(c*float2(2,-2)+float2(-1,1),0,1);\n"
"}\n"
"float3 position_at(int2 pixel) {\n"
"    pixel=clamp(pixel,int2(0,0),int2(size.xy)-1);\n"
"    float z=depth_at(pixel);\n"
"    float2 uv=(float2(pixel)+.5)/size.xy;\n"
"    float4 v=mul(float4(uv*float2(2,-2)+float2(-1,1),z,1),inverse_projection);\n"
"    return v.xyz/max(abs(v.w),1e-8)*sign(v.w);\n"
"}\n"
"float2 ps_main(float4 pixel:SV_Position):SV_Target {\n"
"    int2 p=min(int2(pixel.xy*size.xy/size.zw),int2(size.xy)-1);\n"
"    float raw=depth_at(p);\n"
"    if(raw>=.999999)return float2(1,0); // clear depth / sky\n"
"    float3 center=position_at(p);\n"
"    float3 right=position_at(p+int2(1,0))-center;\n"
"    float3 left=center-position_at(p-int2(1,0));\n"
"    float3 down=position_at(p+int2(0,1))-center;\n"
"    float3 up=center-position_at(p-int2(0,1));\n"
"    float3 dx=abs(right.z)<abs(left.z)?right:left;\n"
"    float3 dy=abs(down.z)<abs(up.z)?down:up;\n"
"    float3 normal=cross(dx,dy);\n"
"    float length2=dot(normal,normal);\n"
"    if(length2<1e-16)return float2(1,abs(center.z));\n"
"    normal*=rsqrt(length2);\n"
"    if(dot(normal,-center)<0)normal=-normal;\n"
"    float radius=max(settings.x,1e-4);\n"
"    float radius_px=min(radius*abs(settings.w)*size.y/(2*max(abs(center.z),1e-4)),96);\n"
"    float obscurance=0;\n"
"    // 32 deterministic spiral taps. Tangent-plane rejection keeps a flat wall clean.\n"
"    [unroll]for(int i=0;i<32;i++) {\n"
"        float fraction=(i+.5)/32.0;\n"
"        float angle=i*2.39996323;\n"
"        int2 q=p+int2(round(float2(cos(angle),sin(angle))*sqrt(fraction)*radius_px));\n"
"        if(any(q<0)||any(q>=int2(size.xy)))continue;\n"
"        float sample_depth=depth_at(q);\n"
"        // Equal-depth samples cannot form a contact shadow on this plane.\n"
"        if(sample_depth>=.999999 || sample_depth==raw)continue;\n"
"        float3 delta=position_at(q)-center;\n"
"        float distance2=dot(delta,delta);\n"
"        // Reject separated layers before angular weighting, on every backend.\n"
"        if(distance2<1e-12 || distance2>=radius*radius)continue;\n"
"        float range=saturate(1-distance2/(radius*radius));\n"
"        obscurance+=saturate((dot(normal,delta)-radius*settings.y)*rsqrt(max(distance2,1e-12)))*range*range;\n"
"    }\n"
"    return float2(saturate(1-settings.z*obscurance/32),abs(center.z));\n"
"}\n"
"Texture2D<float2> obscurance : register(t10);\n"
"Texture2D<float4> scene_color : register(t11);\n"
"float visibility_at(float4 pixel) {\n"
"    int2 full=int2(pixel.xy-origin.xy);\n"
""
"    if(depth_at(full)>=.999999)return 1;\n"
"    float z=abs(position_at(full).z);\n"
"    float2 half_pixel=(float2(full)+.5)*size.zw/size.xy-.5;\n"
"    int2 base=int2(floor(half_pixel));\n"
"    float sum=0,weights=0;\n"
"    [unroll]for(int y=-1;y<=1;y++)[unroll]for(int x=-1;x<=1;x++) {\n"
"        int2 q=clamp(base+int2(x,y),int2(0,0),int2(size.zw)-1);\n"
"        float2 ao=obscurance.Load(int3(q,0));\n"
"        float2 delta=float2(q)-half_pixel;\n"
"        float weight=exp2(-dot(delta,delta))*exp2(-abs(ao.y-z)/max(settings.x*.025,1e-4));\n"
"        if(ao.y<=0 || abs(ao.y-z)>settings.x*.1)weight=0;\n"
"        sum+=ao.x*weight;weights+=weight;\n"
"    }\n"
"    float visibility=weights>1e-6?saturate(sum/weights):1;\n"
"    return visibility;\n"
"}\n"
"float4 composite_main(float4 pixel:SV_Position):SV_Target {\n"
"    float4 color=scene_color.Load(int3(int2(pixel.xy),0));\n"
"    return float4(color.rgb*visibility_at(pixel),color.a);\n"
"}\n"
"float4 multiply_main(float4 pixel:SV_Position):SV_Target {\n"
"    return float4(visibility_at(pixel).xxx,1);\n"
"}\n"
;
#endif
