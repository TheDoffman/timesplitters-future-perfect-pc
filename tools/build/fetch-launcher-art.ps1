#requires -Version 5.1
<# Recover the already-published artwork without executing the downloaded assembly.
   Source artwork stays ignored/local; the immutable release and resource hashes
   are the shared build inputs. The new icon is generated by build-launcher.ps1. #>
[CmdletBinding()]
param([string]$Output)
$ErrorActionPreference = 'Stop'
$project = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if (!$Output) { $Output = Join-Path $project 'build\launcher-art' }
$Output = [IO.Path]::GetFullPath($Output)
$pin = Get-Content -Raw (Join-Path $project 'config\build\launcher-artwork.json') | ConvertFrom-Json
if ($pin.url -notmatch '^https://github\.com/TheDoffman/timesplitters-future-perfect-pc/releases/download/') { throw 'Unexpected artwork source.' }
New-Item -ItemType Directory -Force $Output | Out-Null
$archive = Join-Path $Output 'artwork-source.zip'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
Invoke-WebRequest -UseBasicParsing -Uri $pin.url -OutFile $archive -TimeoutSec 60
if ((Get-Item $archive).Length -gt 16MB -or (Get-FileHash $archive -Algorithm SHA256).Hash.ToLowerInvariant() -ne $pin.sha256) { throw 'Artwork archive checksum mismatch.' }
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [IO.Compression.ZipFile]::OpenRead($archive)
try {
    $entries = @($zip.Entries | Where-Object { $_.FullName -ceq 'Bin/TimeSplitters.App.exe' })
    if ($entries.Count -ne 1 -or $entries[0].Length -gt 16MB) { throw 'Invalid artwork assembly entry.' }
    $inputStream = $entries[0].Open()
    $memory = New-Object IO.MemoryStream
    try { $inputStream.CopyTo($memory); $assembly = [Reflection.Assembly]::ReflectionOnlyLoad($memory.ToArray()) }
    finally { $inputStream.Dispose(); $memory.Dispose() }
    foreach ($resource in $pin.resources.PSObject.Properties) {
        if ($resource.Name -notmatch '^launcher-(banner|backdrop|logo)\.png$') { throw 'Unexpected artwork resource.' }
        $stream = $assembly.GetManifestResourceStream($resource.Name)
        if (!$stream -or $stream.Length -gt 8MB) { throw 'Artwork resource missing or oversized.' }
        $target = Join-Path $Output $resource.Name
        $file = [IO.File]::Create($target)
        try { $stream.CopyTo($file) } finally { $file.Dispose(); $stream.Dispose() }
        if ((Get-FileHash $target -Algorithm SHA256).Hash.ToLowerInvariant() -ne $resource.Value) { throw 'Artwork resource checksum mismatch.' }
    }
} finally { $zip.Dispose() }
Remove-Item -LiteralPath $archive
Write-Host 'Published banner, backdrop and logo verified; no downloaded code executed.'
