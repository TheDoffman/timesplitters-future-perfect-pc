"""Embed the pinned SMAA shader, with explicit RHI sampler bindings."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def generated():
    library = (ROOT / 'vendor/smaa/SMAA.hlsl').read_text()
    for name, slot in [('LinearSampler', 0), ('PointSampler', 1)]:
        start = 'SamplerState ' + name + ' {'
        line = next(line for line in library.splitlines() if line.startswith(start))
        library = library.replace(line, f'SamplerState {name} : register(s{slot});')
    wrapper = (ROOT / 'src/graphics/smaa_wrapper.hlsl').read_text()
    source = wrapper.replace('// @SMAA_LIBRARY@', library)
    return ('/* Generated by tools/build/embed-smaa.py. See vendor/smaa/LICENSE.txt. */\n'
            '#ifndef TSFP_SMAA_SHADER_H\n#define TSFP_SMAA_SHADER_H\n'
            'static const char tsfp_smaa_shader[] =\n' +
            '\n'.join(json.dumps(line + '\n') for line in source.splitlines()) +
            ';\n#endif\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'src/graphics/smaa_shader.h'
    expected = generated()
    if args.check:
        if destination.read_text() != expected:
            raise SystemExit('SMAA embedded shader is stale; run tools/build/embed-smaa.py')
    else:
        destination.write_text(expected, newline='\n')
